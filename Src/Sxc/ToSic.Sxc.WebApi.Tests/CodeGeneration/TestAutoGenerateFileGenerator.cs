using ToSic.Sxc.Code.Generate.Sys;

namespace ToSic.Sxc.WebApi.Tests.CodeGeneration;

internal sealed class TestAutoGenerateFileGenerator : IFileGenerator
{
    public FileGeneratorSpecs GeneratorSpecs => field ??= new(this)
    {
        OutputLanguage = "Text",
        OutputType = "Test",
        Description = "Test auto-generate file generator",
        DescriptionHtml = "Test auto-generate file generator",
        Version = "1.0.0",
    };
    internal const string GeneratorName = "TestAutoGenerateGenerator";
    internal const string FileName = "AutoGenerated.txt";

    private readonly List<GenerateFileSetSpecs> _receivedSpecs = [];

    public IReadOnlyList<GenerateFileSetSpecs> ReceivedSpecs => _receivedSpecs;

    public IGeneratedFileSet[] Generate(GenerateFileSetSpecs specs)
    {
        _receivedSpecs.Add(specs);

        return
        [
            new GeneratedFileSet
            {
                Name = "Test auto-generate output",
                Description = "Test auto-generate output",
                Generator = GeneratorSpecs.Name,
                Path = GenerateConstants.PathToAppCode,
                Files =
                [
                    new GeneratedFile
                    {
                        FileName = FileName,
                        Path = "Data",
                        Body = "auto-generated"
                    }
                ]
            }
        ];
    }
}

